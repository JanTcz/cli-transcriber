#!/usr/bin/env node
// A Claude Code PreToolUse hook: an edit to a file that cli-transcriber generated is
// blocked, and the agent is told which source to edit instead. Anything else passes.

import fs from 'node:fs';
import path from 'node:path';

const HEADER = /<!-- Generated by cli-transcriber from (.+?): edit the source/;

let input = '';
for await (const chunk of process.stdin) input += chunk;
let file = null;
let cwd = process.cwd();
try {
  const event = JSON.parse(input);
  file = event.tool_input?.file_path ?? event.tool_input?.notebook_path ?? null;
  cwd = event.cwd ?? cwd;
} catch {
  process.exit(0);
}
if (!file) process.exit(0);
const abs = path.resolve(cwd, file);
let text;
try {
  text = fs.readFileSync(abs, 'utf8');
} catch {
  process.exit(0);
}
const source = HEADER.exec(text)?.[1];
if (!source) process.exit(0);
process.stderr.write(
  `${file} is generated by cli-transcriber from ${source}; an edit here is lost on the next build. ` +
    `Edit ${source} (or the partial it uses) instead, then run: npx -y cli-transcriber@0 build\n`,
);
process.exit(2);
