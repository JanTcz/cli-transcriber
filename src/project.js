// A project: its config, its sources, what they render to, and the files on disk.
// build writes the outputs; check only compares them, for CI.

import fs from 'node:fs';
import path from 'node:path';
import { parse as parseYaml, stringify } from 'yaml';
import { renderBody, validate } from './language.js';
import { KINDS, discover, load, problem } from './load.js';

export const CONFIG = 'transcriber.yaml';
export const HEADER = '<!-- Generated by cli-transcriber from';

/** Where each target puts skills and agents; agents only where the agent reads Markdown ones. */
export function targetDirs(target) {
  if (target === 'claude') return { skills: '.claude/skills', agents: '.claude/agents' };
  if (target === 'codex') return { skills: '.agents/skills', agents: null };
  const plugin = /^plugin:(.+)$/.exec(target);
  if (plugin) return { skills: `${plugin[1]}/skills`, agents: `${plugin[1]}/agents` };
  return null;
}

export class ConfigError extends Error {}

/** transcriber.yaml, or the defaults: sources everywhere, output for Claude Code. */
export function readConfig(root) {
  const file = path.join(root, CONFIG);
  const defaults = { sources: ['.'], targets: ['claude'], tools: [] };
  if (!fs.existsSync(file)) return defaults;
  let raw;
  try {
    raw = parseYaml(fs.readFileSync(file, 'utf8')) ?? {};
  } catch (err) {
    throw new ConfigError(`${CONFIG}: ${err.message.split('\n')[0]}`);
  }
  const config = { ...defaults, ...raw };
  for (const key of Object.keys(raw)) {
    if (!(key in defaults)) throw new ConfigError(`${CONFIG}: unknown setting "${key}"; settings are sources, targets, tools`);
    if (!Array.isArray(raw[key]) || !raw[key].every((v) => typeof v === 'string')) throw new ConfigError(`${CONFIG}: ${key} must be a list of text`);
  }
  for (const t of config.targets) {
    if (!targetDirs(t)) throw new ConfigError(`${CONFIG}: unknown target "${t}"; targets are claude, codex and plugin:<folder>`);
  }
  return config;
}

function frontmatter(doc) {
  const fm = { name: doc.name, description: doc.data.description, ...doc.data.frontmatter };
  return `---\n${stringify(fm, { lineWidth: 0 }).trimEnd()}\n---\n`;
}

/** The Markdown file of a skill or agent. */
export function render(doc, registry) {
  return `${frontmatter(doc)}\n${HEADER} ${doc.file}: edit the source, then run cli-transcriber build. -->\n\n${renderBody(doc, registry)}\n`;
}

/**
 * Reads and checks every source. Returns { config, docs, registry, problems, outputs }:
 * outputs (path → content) only when there are no errors.
 */
export function compile(root) {
  const config = readConfig(root);
  const skip = config.targets.flatMap((t) => Object.values(targetDirs(t)).filter(Boolean));
  const problems = [];
  const docs = [];
  for (const file of discover(root, config.sources, skip)) {
    const { doc, problems: found } = load(root, file);
    problems.push(...found);
    if (doc) docs.push(doc);
  }
  const registry = Object.fromEntries(KINDS.map((k) => [k, new Map()]));
  const unique = [];
  for (const doc of docs) {
    const other = registry[doc.kind].get(doc.name);
    // A second definition is reported and left out: checking it would blame the first.
    if (other) problems.push(problem(doc.file, doc.lineOf(['name']), `${doc.kind} "${doc.name}" is also defined in ${other.file}`));
    else {
      registry[doc.kind].set(doc.name, doc);
      unique.push(doc);
    }
  }
  problems.push(...validate(unique, registry, { tools: config.tools }));
  problems.sort((a, b) => a.file.localeCompare(b.file) || a.line - b.line || a.message.localeCompare(b.message));
  if (problems.some((p) => p.level === 'error')) return { config, docs, registry, problems, outputs: null };

  const outputs = new Map();
  for (const target of config.targets) {
    const dirs = targetDirs(target);
    for (const doc of registry.skill.values()) outputs.set(`${dirs.skills}/${doc.name}/SKILL.md`, render(doc, registry));
    if (dirs.agents) for (const doc of registry.agent.values()) outputs.set(`${dirs.agents}/${doc.name}.md`, render(doc, registry));
  }
  return { config, docs, registry, problems, outputs };
}

const isGenerated = (content) => content.includes(HEADER);

/** Generated files in the target folders that no source produces any more. */
function stale(root, config, outputs) {
  const found = [];
  for (const target of config.targets) {
    const dirs = targetDirs(target);
    const candidates = [];
    const skills = path.join(root, dirs.skills);
    if (fs.existsSync(skills)) for (const d of fs.readdirSync(skills)) candidates.push(`${dirs.skills}/${d}/SKILL.md`);
    const agents = dirs.agents && path.join(root, dirs.agents);
    if (agents && fs.existsSync(agents)) for (const f of fs.readdirSync(agents)) if (f.endsWith('.md')) candidates.push(`${dirs.agents}/${f}`);
    for (const rel of candidates) {
      const abs = path.join(root, rel);
      if (!outputs.has(rel) && fs.existsSync(abs) && isGenerated(fs.readFileSync(abs, 'utf8'))) found.push(rel);
    }
  }
  return found.sort();
}

/**
 * What would change on disk: { create, update, unchanged, remove, conflicts }. A conflict
 * is a file at an output path that cli-transcriber didn't write: never overwritten.
 */
export function plan(root, compiled) {
  const out = { create: [], update: [], unchanged: [], remove: [], conflicts: [] };
  for (const [rel, content] of compiled.outputs) {
    const abs = path.join(root, rel);
    if (!fs.existsSync(abs)) out.create.push(rel);
    else {
      const current = fs.readFileSync(abs, 'utf8');
      if (current === content) out.unchanged.push(rel);
      else if (!isGenerated(current)) out.conflicts.push(rel);
      else out.update.push(rel);
    }
  }
  out.remove = stale(root, compiled.config, compiled.outputs);
  return out;
}

/** Writes the outputs and removes stale ones; conflicts stop it unless forced. */
export function build(root, { force = false } = {}) {
  const compiled = compile(root);
  if (!compiled.outputs) return { op: 'build', ok: false, problems: compiled.problems };
  const changes = plan(root, compiled);
  if (changes.conflicts.length && !force) {
    const problems = changes.conflicts.map((rel) => problem(rel, 1, 'exists and was not generated by cli-transcriber; move it into a source, or run with --force to overwrite it'));
    return { op: 'build', ok: false, problems: [...compiled.problems, ...problems] };
  }
  for (const rel of [...changes.create, ...changes.update, ...changes.conflicts]) {
    fs.mkdirSync(path.dirname(path.join(root, rel)), { recursive: true });
    fs.writeFileSync(path.join(root, rel), compiled.outputs.get(rel));
  }
  for (const rel of changes.remove) {
    fs.rmSync(path.join(root, rel));
    const dir = path.dirname(path.join(root, rel));
    if (rel.endsWith('/SKILL.md') && fs.readdirSync(dir).length === 0) fs.rmdirSync(dir);
  }
  return {
    op: 'build',
    ok: true,
    problems: compiled.problems,
    written: [...changes.create, ...changes.update, ...changes.conflicts].sort(),
    removed: changes.remove,
    unchanged: changes.unchanged.length,
  };
}

/** Everything valid and every output up to date, without writing: for CI and hooks. */
export function check(root) {
  const compiled = compile(root);
  if (!compiled.outputs) return { op: 'check', ok: false, problems: compiled.problems, outdated: [] };
  const changes = plan(root, compiled);
  const outdated = [
    ...changes.create.map((p) => ({ path: p, why: 'missing' })),
    ...changes.update.map((p) => ({ path: p, why: 'differs from its source (edited by hand, or the source changed)' })),
    ...changes.conflicts.map((p) => ({ path: p, why: 'not generated by cli-transcriber' })),
    ...changes.remove.map((p) => ({ path: p, why: 'its source is gone' })),
  ].sort((a, b) => a.path.localeCompare(b.path));
  return { op: 'check', ok: outdated.length === 0, problems: compiled.problems, outdated };
}

/** One skill or agent, rendered, without writing anything. */
export function show(root, name) {
  const compiled = compile(root);
  if (!compiled.outputs) return { op: 'show', ok: false, problems: compiled.problems };
  const [kind, bare] = name.includes(':') ? name.split(':', 2) : [null, name];
  const doc = ['skill', 'agent'].filter((k) => !kind || k === kind).map((k) => compiled.registry[k].get(bare)).find(Boolean);
  if (!doc) return { op: 'show', ok: false, problems: [...compiled.problems, problem(CONFIG, 0, `no skill or agent named "${bare}"`)] };
  return { op: 'show', ok: true, problems: compiled.problems, kind: doc.kind, name: doc.name, source: doc.file, content: render(doc, compiled.registry) };
}
