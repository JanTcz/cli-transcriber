// The package, the plugin and its hook agree with each other.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import * as api from '../src/index.js';
import { USAGE } from '../src/cli.js';
import { check } from '../src/project.js';
import { BASIC, project } from './helpers.js';

const url = (p) => new URL(`../${p}`, import.meta.url);
const json = (p) => JSON.parse(fs.readFileSync(url(p), 'utf8'));
const pkg = json('package.json');
const GUARD = url('agents/claude/guard.mjs').pathname;

test('the entry point exports the API', () => {
  for (const name of ['KINDS', 'discover', 'load', 'validate', 'expandText', 'renderBody', 'KNOWN_TOOLS', 'CONFIG', 'compile', 'build', 'check', 'show', 'render', 'readConfig', 'targetDirs', 'main', 'init', 'VERSION']) {
    assert.ok(name in api, name);
  }
});

test('both plugin manifests have the package version and point at files that exist', () => {
  const claude = json('agents/.claude-plugin/plugin.json');
  const codex = json('agents/.codex-plugin/plugin.json');
  for (const m of [claude, codex]) {
    assert.equal(m.name, pkg.name);
    assert.equal(m.version, pkg.version);
    assert.equal(m.license, pkg.license);
  }
  for (const [dir, p] of [['agents', claude.hooks], ['agents', codex.skills], ['agents', codex.interface.logo]]) {
    assert.match(p, /^\.\//);
    assert.ok(fs.existsSync(url(`${dir}/${p.slice(2)}`)), p);
  }
  const hooks = json('agents/claude/hooks.json');
  assert.match(hooks.hooks.PreToolUse[0].hooks[0].command, /\$\{CLAUDE_PLUGIN_ROOT\}\/claude\/guard\.mjs/);
});

test('the skill names this major version and only commands that exist', () => {
  const skill = fs.readFileSync(url(`agents/skills/${pkg.name}/SKILL.md`), 'utf8');
  const fm = /^---\nname: (.+)\ndescription: (.+)\n---\n/.exec(skill);
  assert.equal(fm[1], pkg.name);
  assert.ok(fm[2].length < 1024);
  const npx = `npx -y ${pkg.name}@${pkg.version.split('.')[0]}`;
  for (const [, cmd] of skill.matchAll(new RegExp(`${npx.replace(/[.@]/g, '\\$&')} (\\w+)`, 'g'))) assert.match(USAGE, new RegExp(`\\n  ${cmd} `), cmd);
  assert.ok(skill.includes(`${npx} build`) && skill.includes(`${npx} check`));
});

test('the guard hook blocks edits to generated files and lets everything else through', (t) => {
  const dir = project(t, BASIC);
  api.build(dir);
  const run = (event) => spawnSync(process.execPath, [GUARD], { input: typeof event === 'string' ? event : JSON.stringify(event), encoding: 'utf8' });
  const blocked = run({ tool_name: 'Edit', cwd: dir, tool_input: { file_path: '.claude/skills/review/SKILL.md' } });
  assert.equal(blocked.status, 2);
  assert.match(blocked.stderr, /generated by cli-transcriber from skills\/review\.skill\.yaml; .*Edit skills\/review\.skill\.yaml/);
  assert.equal(run({ tool_input: { file_path: path.join(dir, 'skills/review.skill.yaml') } }).status, 0);
  assert.equal(run({ tool_input: { notebook_path: path.join(dir, 'x.ipynb') } }).status, 0);
  assert.equal(run({ tool_input: { file_path: path.join(dir, '.claude/agents/checker.md') } }).status, 2);
  assert.equal(run({ tool_input: {} }).status, 0);
  assert.equal(run('not json').status, 0);
});

test('the example in examples/team is up to date', () => {
  const r = check(url('examples/team').pathname);
  assert.deepEqual([r.ok, r.problems, r.outdated], [true, [], []]);
});

test('the npm package ships the plugin', () => {
  assert.deepEqual(pkg.files, ['src', 'bin', 'agents']);
  assert.equal(pkg.bin[pkg.name], './bin/cli-transcriber.js');
  assert.deepEqual(Object.keys(pkg.dependencies), ['yaml']);
  assert.ok(check(project({ after() {} }, BASIC)).outdated.length === 2);
});
